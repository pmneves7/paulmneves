"""Regenerate js/laue-xray-data.js with xraylib 4.3.0."""

import json
from math import exp, log
from pathlib import Path

import xraylib as xrl


def edge_knots(elements, lo, hi):
    knots = []
    for z in elements:
        for shell in range(xrl.Q3_SHELL + 1):
            try:
                edge = xrl.EdgeEnergy(z, shell)
            except ValueError:
                continue
            if lo < edge < hi:
                knots.extend(e for e in (edge - 1e-6, edge, edge + 1e-6) if lo < e < hi)
    return knots


def sample(function, lo, hi, extra, absolute, relative):
    """Adapt linear interpolation to resolved features and absorption edges."""
    knots = sorted({lo, hi, *extra, *(lo * exp(log(hi / lo) * i / 48) for i in range(1, 48))})

    def subdivide(a, fa, b, fb, depth):
        if depth:
            for t in (.25, .5, .75):
                value = function(a + t * (b - a))
                linear = [x + t * (y - x) for x, y in zip(fa, fb)]
                if any(abs(v - u) > absolute + relative * abs(v) for u, v in zip(linear, value)):
                    m = (a + b) / 2
                    fm = function(m)
                    yield from subdivide(a, fa, m, fm, depth - 1)
                    yield from subdivide(m, fm, b, fb, depth - 1)
                    return
        yield [a, *fa]

    rows = []
    for a, b in zip(knots, knots[1:]):
        rows.extend(subdivide(a, function(a), b, function(b), 16))
    rows.append([hi, *function(hi)])
    return [float(f"{v:.{10 if i == 0 else 6}g}") for row in rows for i, v in enumerate(row)]


def main():
    if xrl.__version__ != "4.3.0":
        raise SystemExit("Install xraylib==4.3.0 to reproduce this table.")
    lo, hi = .5, 300
    materials = ["Air, Dry (near sea level)", "Be", "C10H8O4"]
    attenuation = sample(
        lambda e: [xrl.CS_Total_CP(m, e) for m in materials],
        lo, hi, edge_knots([4, 6, 7, 8, 18], lo, hi), 0, .004,
    )
    dispersion, rayleigh = {}, {}
    for z in range(1, 99):
        element = xrl.AtomicNumberToSymbol(z)
        # xraylib Fii has the opposite sign from f'' with exp(+2πi h·r).
        dispersion[element] = sample(
            lambda e: [xrl.Fi(z, e), -xrl.Fii(z, e)],
            lo, hi, edge_knots([z], lo, hi), .04, .003,
        )
        rayleigh[element] = sample(lambda s: [xrl.FF_Rayl(z, s)], 2, 25, [], .001, .003)

    def encode(value):
        return json.dumps(value, separators=(",", ":"))

    target = Path(__file__).resolve().parent.parent / "js" / "laue-xray-data.js"
    lines = [
        "// Generated by scripts/generate-laue-xray-data.py from xraylib 4.3.0.",
        "// https://doi.org/10.1016/j.sab.2011.09.011 | License: laue-xray-data.LICENSE.txt",
        "// Attenuation rows: [keV, air, Be, PET] in cm²/g.",
        "// Dispersion rows: [keV, f′, f″]; Rayleigh rows: [s (Å⁻¹), f₀].",
        "(function (global) {",
        '  "use strict";',
        "  global.LaueXrayData = {",
        "    attenuation: " + encode(attenuation) + ",",
    ]
    for name, data in (("dispersion", dispersion), ("rayleigh", rayleigh)):
        lines.append(f"    {name}: {{")
        lines.extend(f"      {key}: {encode(rows)}," for key, rows in data.items())
        lines.append("    },")
    lines += ["  };", '})(typeof window !== "undefined" ? window : globalThis);', ""]
    target.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
